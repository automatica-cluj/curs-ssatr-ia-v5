/**
 * Client side of the taxi demo.
 *
 * Message flow:
 * 1. Client publishes its name on the fanout exchange; every driver queue receives a copy.
 * 2. A driver who takes the order sends its name to this client's own queue.
 * 3. When the order is finished the driver sends "COMPLETE driver" to the same queue.
 * If a second driver also accepted the order, the client answers it with "REJECTED client".
 *
 * @author mihai
 */
