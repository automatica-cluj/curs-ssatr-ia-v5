    /**
     * Wait for messages to be received on client queue. On this queue we receive name of the driver who confirm our order request OR confirm order complete.
     * 
     * IMPORTANT - Connecting to the broker is a slow network operation, so we call this from a separate thread to keep the UI responsive (notice current class implement Runnable interface, implements run() and run() calls this method).
     * basicConsume() itself does not block: it returns immediately and the RabbitMQ library calls handle() on its own thread for each message.  
     * @throws IOException
     * @throws TimeoutException 
     */
    public void startReceiver() throws IOException, TimeoutException{
        ConnectionFactory factory = new ConnectionFactory();
        factory.setHost("control.aut.utcluj.ro");
        factory.setPort(11156);
        factory.setUsername("***");
        factory.setPassword("***");
        Connection connection = factory.newConnection();
        Channel channel = connection.createChannel();

        //arguments: durable=false, exclusive=false, autoDelete=false. Declaring a queue which already exists has no effect if the arguments are the same.
        channel.queueDeclare(CLIENT_QUEUE_NAME, false, false, false, null);
        System.out.println(" [*] Waiting for messages. To exit press CTRL+C");

        System.out.println("Start consuming messages...");
        //autoAck=true: a message counts as processed as soon as it is delivered. "this" is the DeliverCallback (see handle()); the empty lambda is the callback for a cancelled consumer, not used here.
        channel.basicConsume(CLIENT_QUEUE_NAME, true, this, consumerTag -> { });
    }
    
    /**
     * Request a new order by sending name of the client. We consider name of the client to be unique, no validation is done on this. 
     * Requests are sent to fanout queue which is responsbile to redirect request to ALL drivers queues. 
     * @param msg
     * @throws Exception 
     */
    public void sendRequestOrderToDrivers(String msg) throws Exception{
        ConnectionFactory factory = new ConnectionFactory();
        factory.setHost("control.aut.utcluj.ro");
        factory.setPort(11156);
        factory.setUsername("***");
        factory.setPassword("***");
        try (Connection connection = factory.newConnection();
            Channel channel = connection.createChannel()) {
            //publish on the exchange, not on a queue. The routing key "" is ignored by a fanout exchange, which copies the message to all bound queues.
            channel.basicPublish(FANOUT_QUEUE_NAME_BOOKING, "", null, msg.getBytes());
            System.out.println(" [x] Sent '" + msg + "'");
        }
    }

    /**
     * Tell a driver the order is already assigned to another driver. Can happen when two drivers accept the same order at the same time.
     * @param driver name of the driver who lost the order
     */
    private void sendRejectionToDriver(String driver) {
        ConnectionFactory factory = new ConnectionFactory();
        factory.setHost("control.aut.utcluj.ro");
        factory.setPort(11156);
        factory.setUsername("***");
        factory.setPassword("***");
        try (Connection connection = factory.newConnection();
            Channel channel = connection.createChannel()) {
            //exchange "" is the default exchange: it delivers directly to the queue with the name given as routing key
            channel.basicPublish("", TaxiNames.DRIVER_QUEUE+driver, null, ("REJECTED "+clientID).getBytes());
        } catch (IOException | TimeoutException ex) {
            Logger.getLogger(TaxiClientApp.class.getName()).log(Level.SEVERE, null, ex);
        }
    }


